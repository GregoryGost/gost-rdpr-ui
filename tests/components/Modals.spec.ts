import { DOMWrapper, flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import BaseModal from '@/ui/modals/BaseModal.vue'
import ConfirmDialog from '@/ui/modals/ConfirmDialog.vue'

/** Uses real Headless UI dialogs and Teleport; browser E2E separately verifies focus behavior. */
describe('modal components', () => {
  /** Supplies only the missing observation API; geometry and focus are tested in the browser suite. */
  beforeEach(() => {
    /** Accepts Headless UI subscriptions without inventing layout measurements in jsdom. */
    vi.stubGlobal(
      'ResizeObserver',
      class {
        /** No layout changes are generated by this DOM-only fixture. */
        observe() {}
        /** There are no retained target subscriptions to release. */
        unobserve() {}
        /** Teardown is inert because the fixture owns no browser resources. */
        disconnect() {}
      },
    )
  })
  /** Closed content is absent, and opening exposes the title, slot and close event. */
  it('opens BaseModal content and emits close from its button', async () => {
    // wrapper keeps the parent-owned open flag stable while observing the close request.
    const wrapper = mount(BaseModal, {
      attachTo: document.body,
      props: { isOpen: false, title: 'Карточка домена' },
      slots: { default: '<p>example.test</p>' },
    })
    expect(document.body.textContent).not.toContain('example.test')
    await wrapper.setProps({ isOpen: true })
    await flushPromises()
    // body locates real teleported markup instead of assuming it remains under the mount container.
    const body = new DOMWrapper(document.body)
    expect(body.get('[role="dialog"]').text()).toContain('Карточка домена')
    expect(body.get('[role="dialog"]').text()).toContain('example.test')
    await body.get('[role="dialog"] button').trigger('click')
    expect(wrapper.emitted('close')).toEqual([[]])
    expect(wrapper.props('isOpen')).toBe(true)
    await wrapper.setProps({ isOpen: false })
    await flushPromises()
    /** Waits for Headless UI's leave transition to remove the teleported dialog. */
    await vi.waitFor(() => expect(document.body.querySelector('[role="dialog"]')).toBeNull())
  })

  /** Confirmation and cancellation are separate parent requests and retain supplied Russian labels. */
  it('renders ConfirmDialog content and emits confirm and cancel separately', async () => {
    // wrapper uses custom labels to verify that props reach the actionable buttons.
    const wrapper = mount(ConfirmDialog, {
      attachTo: document.body,
      props: {
        isOpen: true,
        title: 'Удалить домен?',
        message: 'Это действие удалит example.test',
        confirmText: 'Удалить',
        cancelText: 'Сохранить',
      },
    })
    await flushPromises()
    // body contains the actual portalled dialog and its real BaseButton descendants.
    const body = new DOMWrapper(document.body)
    expect(body.get('[role="dialog"]').text()).toContain('Удалить домен?')
    expect(body.get('[role="dialog"]').text()).toContain('Это действие удалит example.test')
    expect(
      body
        .findAll('[role="dialog"] button')
        .map(/** Reads the Russian cancel and confirm labels. */ (button) => button.text()),
    ).toEqual(['Сохранить', 'Удалить'])
    await body.findAll('[role="dialog"] button')[1]!.trigger('click')
    expect(wrapper.emitted('confirm')).toEqual([[]])
    expect(wrapper.emitted('cancel')).toBeUndefined()
    await body.findAll('[role="dialog"] button')[0]!.trigger('click')
    expect(wrapper.emitted('cancel')).toEqual([[]])
  })

  /** Pending submission blocks repeated confirmation and button cancellation until the parent releases loading. */
  it('disables ConfirmDialog buttons while loading and restores them afterward', async () => {
    // wrapper starts busy so accidental duplicate submission cannot be hidden by an earlier click.
    const wrapper = mount(ConfirmDialog, {
      attachTo: document.body,
      props: { isOpen: true, title: 'Удалить домен?', message: 'Подтвердите удаление', isLoading: true },
    })
    await flushPromises()
    // body queries the two real button elements across Teleport.
    const body = new DOMWrapper(document.body)
    expect(
      body
        .findAll('[role="dialog"] button')
        .every(
          /** Checks that each native button blocks clicks. */ (button) => button.attributes('disabled') !== undefined,
        ),
    ).toBe(true)
    await body.findAll('[role="dialog"] button')[1]!.trigger('click')
    await body.findAll('[role="dialog"] button')[0]!.trigger('click')
    expect(wrapper.emitted('confirm')).toBeUndefined()
    expect(wrapper.emitted('cancel')).toBeUndefined()
    await wrapper.setProps({ isLoading: false })
    expect(
      body
        .findAll('[role="dialog"] button')
        .every(
          /** Checks that loading released each native button. */ (button) =>
            button.attributes('disabled') === undefined,
        ),
    ).toBe(true)
  })
})
